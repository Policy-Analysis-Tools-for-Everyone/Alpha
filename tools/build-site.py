"""Build the policymemo.ai site pages from site/.

Posts live in site/blog/posts/*.md, each with a short front matter block:

    ---
    title: Why policymemo.ai asks before it writes
    date: 2026-10-06
    category: why            # why | skills | guides | updates
    skill: problem           # only for posts in the skills series
    summary: One sentence for the index and for link previews.
    draft: true              # optional; drafts are never published
    ---

This writes docs/blog/index.html and one docs/blog/<slug>.html per published
post (the slug is the file name), plus two Atom feeds: feed.xml (every post)
and, once an updates post exists, feed-updates.xml (product updates only). The
feeds are not linked from the page; feed readers find them from the <head>
tags. It also updates the homepage between its blog markers: a Blog link in the
nav and footer, and a "Read the post" link on each skill card, all of which
stay empty until something is published, so the site never shows an empty blog.

It also writes the site's other generated pages, all in the same chrome:
docs/install/ from site/install/, docs/beta/ from site/beta/ (form links and contact
details come from site/beta/config.json), and docs/updates/ from site/updates/changelog.md.

    python3 tools/build-site.py              # publish
    python3 tools/build-site.py --drafts OUT # preview everything, drafts included, into OUT

Requires the `markdown` package (pip install markdown).
"""
