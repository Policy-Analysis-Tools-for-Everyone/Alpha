def build_index(posts, css, home):
    by_skill = {p["skill"]: p for p in posts if p.get("skill")}
    rows = "".join(
        f'<li class="post-row" data-cat="{p["category"]}" data-rise><a href="{p["slug"]}.html">'
        f'<span class="meta">{cat_label(p, after=" · ")}{nice_date(p["date_obj"])}</span>'
        f'<span class="t">{html.escape(p["title"])}</span><span class="s">{html.escape(p["summary"])}</span></a></li>'
        for p in posts)
    latest = (f'<ul class="posts">{rows}</ul>' if posts else
              '<p class="empty">The first post is on its way. In the meantime, <a href="' + home + '">see what policymemo.ai does</a>.</p>')
