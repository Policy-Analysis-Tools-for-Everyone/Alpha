def read_post(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        raise SystemExit(f"{path.name}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.split(" #", 1)[0].strip()
    for key in ("title", "date", "category", "summary"):
        if not meta.get(key):
            raise SystemExit(f"{path.name}: front matter needs '{key}'")
    if meta["category"] not in CATEGORIES:
        raise SystemExit(f"{path.name}: category must be one of {', '.join(CATEGORIES)}")
    if meta.get("skill") and meta["skill"] not in {s[0] for s in SKILLS}:
        raise SystemExit(f"{path.name}: unknown skill '{meta['skill']}'")
    meta["date_obj"] = datetime.date.fromisoformat(meta["date"])
    meta["draft"] = meta.get("draft", "").lower() == "true"
    meta["slug"] = path.stem
    meta["body"] = markdown.markdown(m.group(2), extensions=["extra", "smarty"])
    words = len(re.sub(r"<[^>]+>", " ", meta["body"]).split())
    meta["minutes"] = max(1, round(words / 220))
    return meta


def nice_date(d):
    return f"{d.day} {d.strftime('%B %Y')}"


def svg_inline(path, cls, prefix):
    s = path.read_text(encoding="utf-8")
    s = re.sub(r"<\?xml.*?\?>", "", s).strip()
    s = re.sub(r"<title>.*?</title>", "", s)
    s = s.replace('id="pm-', f'id="{prefix}').replace("url(#pm-", f"url(#{prefix}")
    return s.replace("<svg ", f'<svg class="{cls}" aria-hidden="true" ', 1)


